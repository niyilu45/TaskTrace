import {test, expect} from '../../support/fixtures'
import {ProjectFactory} from '../../factories/project'
import {TaskFactory} from '../../factories/task'
import {TaskCommentFactory} from '../../factories/task_comment'
import {TaskRelationFactory} from '../../factories/task_relation'
import {createDefaultViews} from '../project/prepareProjects'

test('outstanding notes and images stay readable without opening task editors', async ({authenticatedPage: page}) => {
	await ProjectFactory.create(1, {title: 'Picture project'})
	await createDefaultViews(1)
	await TaskFactory.create(1, {id: 1, title: 'Parent task'})
	await TaskFactory.create(1, {id: 2, title: 'Child task'}, false)
	await TaskRelationFactory.create(1, {id: 1, task_id: 1, other_task_id: 2, relation_kind: 'subtask'})
	await TaskRelationFactory.create(1, {id: 2, task_id: 2, other_task_id: 1, relation_kind: 'parenttask'}, false)
	const picture = await page.evaluate(() => {
		const canvas = document.createElement('canvas')
		canvas.width = 160; canvas.height = 80
		const context = canvas.getContext('2d')!
		context.fillStyle = '#cbddeb'; context.fillRect(0, 0, 160, 80)
		return canvas.toDataURL('image/png')
	})
	const note = '<aside data-tasktrace-outstanding-note="true" hidden><p>处理说明和备注图片</p><img src="' + picture + '"><p>图片后的补充说明</p></aside>'
	await TaskCommentFactory.create(1, {task_id: 2, comment: '<h3>TaskTrace 遗留事项清单</h3><ul><li data-id="open"><p>Pending picture</p><img src="' + picture + '">' + note + '</li><li data-id="closed" data-done="true"><p>Finished picture</p><img src="' + picture + '">' + note + '</li><li data-id="plain"><p>No note</p></li><li data-id="empty"><p>Empty note</p><aside data-tasktrace-outstanding-note="true" hidden><p><br></p></aside></li></ul>'})
	await page.goto('/projects/1/1?mode=browse')
	const row = page.locator('.progress-row[data-task-id="2"]')
	const image = row.locator('.outstanding-edit-link img').first()
	await expect(image).toBeVisible()
	const projectUrl = page.url()
	async function assertPreview() {
		await expect(page.locator('.image-lightbox')).toBeVisible()
		await expect(page).toHaveURL(projectUrl)
		await expect(page.locator('.task-view')).toHaveCount(0)
		await page.keyboard.press('Escape')
		await expect(page.locator('.image-lightbox')).toHaveCount(0)
		await expect(page).toHaveURL(projectUrl)
	}
	const markedItem = row.locator('.outstanding-edit-link').filter({hasText: 'Pending picture'})
	await expect(markedItem.locator('.outstanding-note-indicator')).toHaveText('(注)')
	await expect(row.locator('.outstanding-edit-link').filter({hasText: 'No note'}).locator('.outstanding-note-indicator')).toHaveCount(0)
	await expect(row.locator('.outstanding-edit-link').filter({hasText: 'Empty note'}).locator('.outstanding-note-indicator')).toHaveCount(0)
	await expect(row.locator('.outstanding-edit-link').filter({hasText: 'Empty note'}).locator('.outstanding-note')).toHaveCount(0)
	const pendingNote = row.locator('.outstanding-note')
	await expect(pendingNote.locator('.readonly-rich-text')).toHaveCount(0)
	await expect(row.locator('.outstanding-edit-link').filter({hasText: 'No note'}).locator('.outstanding-note')).toHaveCount(0)
	await pendingNote.locator('summary').click()
	await expect(pendingNote).toHaveAttribute('open', '')
	await expect(pendingNote.locator('.readonly-rich-text')).toContainText('处理说明和备注图片')
	await expect(pendingNote.locator('.readonly-rich-text')).toContainText('图片后的补充说明')
	await expect(page).toHaveURL(projectUrl)
	await expect(page.locator('.task-view')).toHaveCount(0)
	await pendingNote.locator('img').dblclick()
	await assertPreview()
	await pendingNote.locator('summary').press('Enter')
	await expect(pendingNote).not.toHaveAttribute('open')
	await expect(pendingNote.locator('.readonly-rich-text')).toHaveCount(0)
	await expect(page.locator('.task-view')).toHaveCount(0)
	await image.click()
	await assertPreview()
	await image.dblclick()
	await assertPreview()
	await row.getByRole('button', {name: /展开已完成的遗留事项/}).click()
	await row.locator('.completed-outstanding img').click()
	await assertPreview()
	await expect(row.locator('.completed-outstanding .outstanding-note-indicator')).toHaveText('(注)')
	const completedNote = row.locator('.completed-outstanding .outstanding-note')
	await completedNote.locator('summary').click()
	await expect(completedNote).toContainText('处理说明和备注图片')
	await completedNote.locator('img').click()
	await assertPreview()
	await page.locator('.task-own-progress > summary').click()
	await page.locator('.subtask-outstanding img').first().click()
	await assertPreview()
	await expect(page.locator('.subtask-outstanding .outstanding-note-indicator')).toHaveText('(注)')
	const summaryNote = page.locator('.subtask-outstanding .outstanding-note')
	await summaryNote.locator('summary').click()
	await expect(summaryNote).toContainText('处理说明和备注图片')
	await summaryNote.locator('img').click()
	await assertPreview()
	for (const width of [1280, 390]) {
		await page.setViewportSize({width, height: 900})
		await summaryNote.scrollIntoViewIfNeeded()
		await page.screenshot({path: test.info().outputPath('outstanding-notes-' + width + '.png'), fullPage: true})
	}
	// Clicking the item's text still opens its task card.
	await row.getByText('(注) Pending picture', {exact: true}).click()
	await expect(page).toHaveURL(/\/tasks\/2/)
	await expect(page.locator('.task-view')).toBeVisible()
	const detailsNote = page.locator('.shared-outstanding .outstanding-list:not(.completed-list) .outstanding-note')
	await expect(page.locator('.shared-outstanding .outstanding-list:not(.completed-list) .outstanding-note-indicator')).toHaveText('(注)')
	await detailsNote.locator('summary').click()
	await expect(detailsNote).toContainText('处理说明和备注图片')
	await expect(detailsNote.locator('img')).toBeVisible()
	await page.locator('.shared-outstanding .completed-toggle').click()
	await page.locator('.shared-outstanding .completed-list .outstanding-note summary').click()
	await expect(page.locator('.shared-outstanding .completed-list .outstanding-note')).toContainText('图片后的补充说明')
})
