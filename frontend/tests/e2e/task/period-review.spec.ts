import {readFile} from 'node:fs/promises'
import {test, expect} from '../../support/fixtures'
import {ProjectFactory} from '../../factories/project'
import {createDefaultViews} from '../project/prepareProjects'

test('overview period review filters projects and exports the displayed changes', async ({authenticatedPage: page, apiContext, userToken}, testInfo) => {
	await page.setViewportSize({width: 1280, height: 1000})
	await page.context().addInitScript(() => {Object.defineProperty(window, 'showSaveFilePicker', {value: undefined, configurable: true}); localStorage.setItem('hideAddToHomeScreenMessage', 'true')})
	await ProjectFactory.create(2)
	await createDefaultViews(1); await createDefaultViews(2, 5)
	const api = (process.env.API_URL || '').replace(/\/api\/v1\/?$/, '/api/v2')
	const headers = {Authorization: 'Bearer ' + userToken}
	const create = async (project: number, title: string) => {
		const response = await apiContext.post(api + '/projects/' + project + '/tasks', {headers, data: {title}})
		expect(response.ok()).toBeTruthy(); return response.json()
	}
	const task = await create(1, '周期回顾验收任务'), other = await create(2, '未选择项目的任务')
	for (const [target, text] of [[task.id, '本周完成了接口联调'], [other.id, '此项目应被排除']]) {
		const response = await apiContext.post(api + '/tasks/' + target + '/comments', {headers, data: {comment: '<h3>每日进展 · 2026-01-01</h3><p>' + text + '</p><ul data-type="taskList"><li data-type="taskItem" data-checked="true"><p>已完成清单项</p></li><li data-type="taskItem" data-checked="false"><p>未完成清单项</p></li></ul>'}})
		expect(response.ok()).toBeTruthy()
	}
	const original = '<h3 data-tasktrace-comment-type="outstanding">TaskTrace 遗留事项清单</h3><ul><li data-id="review-item"><p>等待客户确认</p><aside data-tasktrace-outstanding-note="true" hidden><p>原备注：周五确认</p></aside></li></ul>'
	const response = await apiContext.post(api + '/tasks/' + task.id + '/comments', {headers, data: {comment: original}})
	expect(response.ok()).toBeTruthy()
	const item = await response.json()
	expect((await apiContext.put(api + '/tasks/' + task.id + '/comments/' + item.id, {headers, data: {comment: original.replace('原备注：周五确认', '新备注：改为周一确认')}})).ok()).toBeTruthy()
	await page.goto('/')
	await page.getByRole('button', {name: '周期回顾', exact: true}).click()
	const dialog = page.getByRole('dialog')
	await expect(dialog.getByLabel('过去多少天', {exact: true})).toBeChecked()
	await expect(dialog.getByLabel('过去天数（含今天）')).toHaveValue('7')
	await expect(dialog.locator('.review-projects input:checked')).toHaveCount(2)
	await expect(dialog).toHaveCSS('opacity', '1')
	await dialog.screenshot({path: testInfo.outputPath('review-options-desktop.png')})
	await dialog.getByLabel(/全选/).uncheck()
	await dialog.getByRole('button', {name: '查看（新标签页）'}).click()
	await expect(dialog.getByRole('alert')).toHaveText('请至少选择一个项目。')
	await dialog.locator('.review-projects input').first().check()
	await dialog.getByLabel('指定日期范围').check()
	const dates = await dialog.getByLabel('开始日期').inputValue()
	await expect(dialog.getByLabel('结束日期')).not.toHaveValue('')
	await page.setViewportSize({width: 390, height: 844})
	await dialog.screenshot({path: testInfo.outputPath('review-options-mobile.png')})
	await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	await dialog.getByLabel('过去多少天', {exact: true}).check()
	const popupEvent = page.waitForEvent('popup')
	await dialog.getByRole('button', {name: '查看（新标签页）'}).click()
	const report = await popupEvent
	await expect(report.locator('article')).toContainText('本周完成了接口联调')
	await expect(report.locator('article')).toContainText('等待客户确认')
	await expect(report.locator('article')).toContainText('☑ 已完成清单项')
	await expect(report.locator('article')).toContainText('☐ 未完成清单项')
	await expect(report.locator('article')).toContainText('原备注：周五确认')
	await expect(report.locator('article')).toContainText('新备注：改为周一确认')
	await expect(report.locator('article')).not.toContainText('此项目应被排除')
	await expect(report.locator('article')).toContainText(dates)
	await report.setViewportSize({width: 1280, height: 1000})
	await expect(report.locator('.vikunja-loading')).toHaveCount(0)
	await report.screenshot({path: testInfo.outputPath('review-report-desktop.png')})
	await report.setViewportSize({width: 390, height: 844})
	if (await report.locator('.menu-show-button').getAttribute('aria-expanded') === 'true') await report.locator('.menu-show-button').click()
	await expect(report.locator('.menu-show-button')).toHaveAttribute('aria-expanded', 'false')
	await expect.poll(async () => {const box = await report.locator('.menu-container').boundingBox(); return !box || box.x + box.width <= 1}).toBe(true)
	await report.screenshot({path: testInfo.outputPath('review-report-mobile.png')})
	await report.locator('article ul').filter({hasText: '已完成清单项'}).first().screenshot({path: testInfo.outputPath('review-checklist.png')})
	await expect.poll(() => report.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	const downloadEvent = report.waitForEvent('download')
	await report.getByRole('button', {name: '导出 Markdown'}).click()
	const download = await downloadEvent, path = await download.path()
	expect(download.suggestedFilename()).toMatch(/^周期回顾_.*\.md$/)
	const markdown = await readFile(path!, 'utf8')
	expect(markdown).toContain('# 周期回顾'); expect(markdown).toContain('**修改前**'); expect(markdown).toContain('新备注：改为周一确认')
	expect(markdown).not.toContain('此项目应被排除')
	expect(markdown).toContain('- [x] 已完成清单项'); expect(markdown).toContain('- [ ] 未完成清单项')
	await report.reload(); await expect(report.locator('article')).toContainText('本周完成了接口联调')
	// A valid empty historical period is a readable report, not a failed request.
	const url = new URL(report.url()); url.searchParams.set('from', '2000-01-01T00:00:00Z'); url.searchParams.set('until', '2000-01-02T00:00:00Z')
	await report.goto(url.toString()); await expect(report.locator('article')).toContainText('没有可回顾')
})
