import {test, expect} from '../../support/fixtures'
import {ProjectFactory} from '../../factories/project'
import {createDefaultViews} from '../project/prepareProjects'

test('weekly task reminders persist selected weekdays and inclusive range', async ({authenticatedPage: page, apiContext, userToken}, testInfo) => {
	await page.setViewportSize({width: 1280, height: 1000})
	await ProjectFactory.create(1, {id: 1, title: '周期提醒测试'})
	await createDefaultViews(1)
	const api = (process.env.API_URL || '').replace(/\/api\/v1\/?$/, '/api/v2')
	const headers = {Authorization: 'Bearer ' + userToken}
	const created = await apiContext.post(api + '/projects/1/tasks', {headers, data: {title: '每周核对进展', reminders: [{reminder: '2027-01-04T01:30:00Z', relative_period: 0, relative_to: ''}]}})
	expect(created.ok()).toBeTruthy()
	const task = await created.json()
	await page.goto('/tasks/' + task.id)
	const reminder = page.locator('.reminder-input .reminder-detail').first()
	await expect(reminder).toBeVisible()
	await reminder.getByRole('button').click()
	await page.getByRole('button', {name: '按周重复', exact: true}).click()
	const form = page.locator('.weekly-reminder')
	await expect(form).toBeVisible()
	await form.getByLabel('开始日期').fill('2027-01-04')
	await form.getByLabel('结束日期').fill('2027-01-29')
	await form.getByLabel('提醒时间', {exact: true}).fill('09:30')
	for (const day of ['周一','周二','周三','周四','周五','周六','周日']) await form.getByLabel(day, {exact: true}).setChecked(['周一','周三','周五'].includes(day))
	await expect(page.locator('.popup.is-open')).toHaveCSS('opacity', '1')
	await page.locator('.popup.is-open').screenshot({path: testInfo.outputPath('weekly-web-desktop.png')})
	await page.getByRole('button', {name: /^(Confirm|确认)$/}).click()
	await expect(reminder).toContainText('周一、周三、周五')
	await expect.poll(async () => {
		const response = await apiContext.get(api + '/tasks/' + task.id, {headers})
		return (await response.json()).reminders?.[0]?.repeat_rule
	}).toContain('"endDate":"2027-01-29"')
	await page.reload()
	await expect(reminder).toContainText('2027-01-04 至 2027-01-29')
	await reminder.getByRole('button').click()
	await expect(form.getByLabel('周三', {exact: true})).toBeChecked()
	await form.getByLabel('结束日期').fill('2027-01-03')
	await expect(form.getByRole('alert')).toContainText('结束日期不能早于开始日期')
	await expect(page.getByRole('button', {name: /^(Confirm|确认)$/})).toBeDisabled()
	await form.getByLabel('结束日期').fill('2027-01-29')
	await page.setViewportSize({width: 390, height: 844})
	// Reopen after the responsive popup becomes a bottom sheet.
	await page.keyboard.press('Escape')
	await reminder.getByRole('button').click()
	await expect(form).toBeVisible()
	await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
	await expect(page.getByRole('dialog')).toHaveCSS('opacity', '1')
	await page.screenshot({path: testInfo.outputPath('weekly-web-mobile.png')})
})

test('outstanding reminders retain their rule through unrelated content edits', async ({authenticatedPage: page, apiContext, userToken}) => {
	await ProjectFactory.create(1, {id: 1})
	await createDefaultViews(1)
	const api = (process.env.API_URL || '').replace(/\/api\/v1\/?$/, '/api/v2')
	const headers = {Authorization: 'Bearer ' + userToken}
	const created = await apiContext.post(api + '/projects/1/tasks', {headers, data: {title: '遗留事项提醒'}})
	expect(created.ok()).toBeTruthy()
	const task = await created.json()
	const comment = await apiContext.post(api + '/tasks/' + task.id + '/comments', {headers, data: {comment: '<h3 data-tasktrace-comment-type="outstanding">TaskTrace 遗留事项清单</h3><ul><li data-id="weekly-item" data-priority="7">周期核对遗留事项</li></ul>'}})
	expect(comment.ok()).toBeTruthy()
	await page.goto('/tasks/' + task.id)
	const row = page.locator('.shared-outstanding .outstanding-list > li').first()
	await expect(row).toContainText('周期核对遗留事项')
	await row.getByRole('button', {name: /Add.*reminder|添加提醒/i}).click()
	await page.getByRole('button', {name: '按周重复', exact: true}).click()
	const form = page.locator('.weekly-reminder')
	await form.getByLabel('开始日期').fill('2027-01-04')
	await form.getByLabel('结束日期').fill('2027-01-29')
	await form.getByLabel('周一', {exact: true}).check()
	await page.getByRole('button', {name: /^(Confirm|确认)$/}).click()
	await expect(row).toContainText('每周')
	await row.getByLabel(/填写完成度/).selectOption('40')
	await page.reload()
	await expect(row).toContainText('每周')
	await expect(row).toContainText('40%')
	await row.getByRole('button', {name: '移除提醒', exact: true}).click()
	await expect(row.getByRole('button', {name: '移除提醒', exact: true})).toHaveCount(0)
	await page.reload()
	await expect(row.getByRole('button', {name: '移除提醒', exact: true})).toHaveCount(0)
})
