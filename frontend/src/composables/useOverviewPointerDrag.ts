import {onBeforeUnmount, ref} from 'vue'

// Pointer dragging keeps the browser's normal wheel scrolling available. Native
// HTML drag-and-drop starts an OS drag loop, which can swallow wheel events.
export function useOverviewPointerDrag<T>(options: {
	canStart: (item: T) => boolean,
	start: (item: T) => void,
	move: (x: number, y: number) => void,
	drop: () => void,
	end: () => void,
}) {
	const position = ref({x: 0, y: 0})
	let candidate: {item: T, id: number, x: number, y: number, element: HTMLElement} | null = null
	let active = false
	let scrollFrame = 0
	let clickTimer: ReturnType<typeof setTimeout> | undefined

	function clearClickGuard() {
		clearTimeout(clickTimer)
		window.removeEventListener('click', suppressClick, true)
		window.removeEventListener('pointerup', releaseClickGuard, true)
		window.removeEventListener('pointerdown', clearClickGuard, true)
	}
	function releaseClickGuard() { clickTimer = setTimeout(clearClickGuard, 0) }
	function suppressClick(event: MouseEvent) {
		event.preventDefault()
		event.stopImmediatePropagation()
		clearClickGuard()
	}
	function finish(released = false) {
		const current = candidate
		candidate = null
		if (current?.element.hasPointerCapture(current.id)) current.element.releasePointerCapture(current.id)
		window.removeEventListener('pointermove', move, true)
		window.removeEventListener('pointerup', release, true)
		window.removeEventListener('pointercancel', cancel, true)
		window.removeEventListener('blur', cancel)
		window.removeEventListener('keydown', keydown, true)
		window.removeEventListener('scroll', scroll, true)
		cancelAnimationFrame(scrollFrame)
		scrollFrame = 0
		document.documentElement.classList.remove('overview-task-dragging')
		if (active) {
			active = false
			options.end()
			// Suppress only the click generated by the drag's mouse release.
			if (released) releaseClickGuard()
			else {
				window.addEventListener('pointerup', releaseClickGuard, true)
				window.addEventListener('pointerdown', clearClickGuard, true)
			}
		}
	}
	function cancel() { finish() }
	function keydown(event: KeyboardEvent) {
		if (event.key !== 'Escape') return
		event.preventDefault()
		event.stopPropagation()
		finish()
	}
	function move(event: PointerEvent) {
		if (!candidate || event.pointerId !== candidate.id) return
		if (!(event.buttons & 1)) { finish(true); return }
		if (!active) {
			if (Math.hypot(event.clientX - candidate.x, event.clientY - candidate.y) < 6) return
			if (!options.canStart(candidate.item)) { finish(); return }
			active = true
			window.addEventListener('click', suppressClick, true)
			document.documentElement.classList.add('overview-task-dragging')
			options.start(candidate.item)
		}
		event.preventDefault()
		position.value = {x: event.clientX, y: event.clientY}
		options.move(event.clientX, event.clientY)
	}
	function scroll() {
		if (!active || scrollFrame) return
		scrollFrame = requestAnimationFrame(() => {
			scrollFrame = 0
			if (active) options.move(position.value.x, position.value.y)
		})
	}
	function release(event: PointerEvent) {
		if (!candidate || event.pointerId !== candidate.id) return
		try {
			if (active) {
				event.preventDefault()
				options.move(event.clientX, event.clientY)
				options.drop()
			}
		} finally { finish(true) }
	}
	function begin(item: T, event: PointerEvent) {
		if (event.button !== 0 || !event.isPrimary || event.pointerType !== 'mouse' || event.ctrlKey || event.metaKey || !options.canStart(item)) return
		finish()
		clearClickGuard()
		const element = event.currentTarget as HTMLElement
		candidate = {item, id: event.pointerId, x: event.clientX, y: event.clientY, element}
		element.setPointerCapture(event.pointerId)
		window.addEventListener('pointermove', move, {capture: true, passive: false})
		window.addEventListener('pointerup', release, true)
		window.addEventListener('pointercancel', cancel, true)
		window.addEventListener('blur', cancel)
		window.addEventListener('keydown', keydown, true)
		window.addEventListener('scroll', scroll, true)
	}
	onBeforeUnmount(() => { finish(); clearClickGuard() })
	return {begin, position}
}
